"""Emit kernel-checkable inverse certificates from the existing prime-cover data.

This generator is not trusted: each emitted modular identity is proved by rfl.
It writes Lean source to stdout; it does not modify the repository.
"""

import argparse
import math
from pathlib import Path
import re


HERE = Path(__file__).resolve().parent


def numbers(name, xs):
    rows = ["  " + ", ".join(map(str, xs[i:i + 9])) for i in range(0, len(xs), 9)]
    return f"def {name} : List ℕ := [\n" + ",\n".join(rows) + "\n]\n\n"


def segment(name, xs, modulus, small=False):
    result = numbers(name, xs)
    if not small:
        inverse = pow(math.prod(xs), -1, modulus)
        result += f"private def {name}Inverse : ℕ :=\n  {inverse}\n\n"
    result += f"lemma {name}_segment : CertifiedSegment {name} {xs[0]} {xs[-1]} := by\n"
    if small:
        result += f"  refine ⟨?_, ?_, rfl, rfl⟩\n  · norm_num [{name}]\n"
    else:
        result += (f"  refine ⟨primes_of_product_inverse (u := {name}Inverse)\n"
                   "    (by decide) (by rfl), ?_, rfl, rfl⟩\n")
    result += "  · unfold GapStep\n    decide\n\n"
    return result


def generate(start, count, part):
    core = (HERE / 'Erdos1058Core.lean').read_text()
    table = core.split('def cubicTrialDivisorChunks : List (List ℕ) :=', 1)[1]
    table = table.split('lemma cubicTrialDivisorChunks_eq_computed', 1)[0]
    divisors = list(map(int, re.findall(r'\d+', table)))
    assert len(divisors) == 784
    modulus = 2 * math.prod(divisors)
    batches = []
    for index in range(start, start + count):
        source = (HERE / f'Erdos1058PrimeGapData{index:03d}.lean').read_text()
        chunks = re.findall(r'def primeGapData_\d+_\d+ : List ℕ := \[([^]]*)\]', source)
        xs = [int(x) for chunk in chunks for x in re.findall(r'\d+', chunk)]
        assert xs and all(a < b <= a + 210 for a, b in zip(xs, xs[1:]))
        if batches:
            assert batches[-1][1][-1] < xs[0] <= batches[-1][1][-1] + 210
        batches.append((index, xs))

    result = ("import ErdosProblems.Erdos1058.Erdos1058PrimeBatch\n\n"
              "/- Generated by generate_prime_batches.py. Every arithmetic witness is\n"
              "checked by the kernel; no compiled-evaluation axioms are used. -/\n"
              "set_option Elab.async false\n"
              "-- Each batch has at most 500 entries.\n"
              "set_option maxRecDepth 4096\n"
              "-- Modular-inverse witnesses are single large natural-number literals.\n"
              "set_option linter.style.longLine false\n\n"
              "namespace Erdos1058.PrimeGap210Certificate\n\n")
    for index, xs in batches:
        name = f'primeBatch{index:03d}'
        small = [p for p in xs if p <= max(divisors)]
        large = [p for p in xs if p > max(divisors)]
        if small:
            assert small + large == xs and large
            result += segment(name + 'Small', small, modulus, small=True)
            result += segment(name + 'Large', large, modulus)
            result += (f'def {name} : List ℕ := {name}Small ++ {name}Large\n\n'
                       f'lemma {name}_segment : CertifiedSegment {name} {xs[0]} {xs[-1]} :=\n'
                       f'  {name}Small_segment.append {name}Large_segment (by unfold GapStep; decide)\n\n')
        else:
            result += segment(name, xs, modulus)

    first = batches[0][1][0]
    for step, (index, xs) in enumerate(batches):
        name = f'primeBatch{index:03d}'
        cover = f'primeBatchCover{part}Step{step}'
        previous = f'primeBatchCover{part}Step{step - 1}'
        value = name if step == 0 else f'{previous} ++ {name}'
        result += f'private def {cover} : List ℕ := {value}\n\n'
        result += (f'private lemma {cover}_segment :\n'
                   f'    CertifiedSegment {cover} {first} {xs[-1]} := by\n'
                   f'  unfold {cover}\n')
        result += (f'  exact {name}_segment\n\n' if step == 0 else
                   f'  exact {previous}_segment.append {name}_segment (by unfold GapStep; decide)\n\n')
    result += (f'def primeBatchCover{part} : List ℕ := {cover}\n\n'
               f'lemma primeBatchCover{part}_segment :\n'
               f'    CertifiedSegment primeBatchCover{part} {first} {xs[-1]} :=\n'
               f'  {cover}_segment\n\n'
               'end Erdos1058.PrimeGap210Certificate\n')
    return result


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--start', type=int, required=True)
    parser.add_argument('--count', type=int, required=True)
    parser.add_argument('--part', type=int, required=True)
    args = parser.parse_args()
    print(generate(args.start, args.count, args.part), end='')
