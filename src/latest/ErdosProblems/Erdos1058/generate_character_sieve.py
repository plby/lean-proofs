#!/usr/bin/env python3
"""Emit kernel-checked character tables or periodic-sieve witnesses to stdout.

--table emits the shared cubic-character classes.  --gaps / --single emit
certificates using these classes.  The generator itself is not trusted.
"""

import argparse
import math

BOUND = 36_000_000
MODULI = [7, 13, 19, 31, 37, 43, 61, 67, 73, 79, 97, 103, 109, 127, 139,
          151, 157, 163, 181, 193, 199, 211, 223, 229, 241, 271, 277, 283,
          307, 313, 331, 337, 349, 367, 373, 379, 397, 409, 421, 433]


def proper_divisor(n):
    return next((s for s in range(2, math.isqrt(n) + 1) if n % s == 0), None)


def exceptions_for(d, kind):
    """Find witnesses independently of the character-class implementation."""
    bits = (1 << BOUND) - 1
    for r in MODULI:
        def accepting(p):
            q = p + d
            base = p * q if kind == 0 else p * q * q if kind == 1 else p
            return p % r != 0 and q % r != 0 and pow(base, (r - 1) // 3, r) == 1

        mask = sum(1 << p for p in range(r) if accepting(p))
        width = r
        while width < BOUND:
            mask |= mask << width
            width *= 2
        bits &= mask
    exceptions = []
    while bits:
        one = bits & -bits
        p = one.bit_length() - 1
        bits ^= one
        s = 0 if p <= 433 else proper_divisor(p)
        second = False
        if s is None:
            s = proper_divisor(p + d)
            second = True
        if s is None:
            raise ValueError(f"Unexplained surviving prime pair: {p}, {p + d}")
        exceptions.append((p, s, second))
    return exceptions


def header(module, part=None):
    print(f"import ErdosProblems.Erdos1058.{module}")
    if part is not None:
        print(f"import ErdosProblems.Erdos1058.Erdos1058PrimeBatchData{part}")
        print("\n/- The matching prime batch keeps the expensive certificates in four build lanes. -/")
    print()
    print("/- Generated by generate_character_sieve.py; every witness is kernel-checked. -/")
    print("set_option Elab.async false\nset_option maxRecDepth 4096")
    print("set_option linter.style.longLine false\n")
    print("namespace Erdos1058.PeriodicSieveCertificate\n")


def table():
    header("Erdos1058CharacterSieve")
    for r in MODULI:
        values = sorted({pow(p, (r - 1) // 3, r) for p in range(1, r)})
        assert len(values) == 3 and values[0] == 1
        masks = [sum(1 << p for p in range(1, r)
                     if pow(p, (r - 1) // 3, r) == v) for v in values]
        depth = 0
        while r * 2 ** depth < BOUND:
            depth += 1
        print(f"private def characterRow{r} : CharacterRow :=")
        print(f"  ⟨{r}, {depth}, [" + ", ".join(
            f"⟨{v}, {m}⟩" for v, m in zip(values, masks)) + "]⟩\n")
        print(f"private lemma characterRow{r}_checked : characterCheck characterRow{r} = true := by rfl\n")
    print("def characterRows : List CharacterRow := [")
    print("  " + ", ".join(f"characterRow{r}" for r in MODULI) + "]\n")
    print("lemma characterRows_checked : characterRows.all characterCheck = true := by")
    print("  simp only [characterRows, List.all_cons, List.all_nil, Bool.and_true,")
    print("    " + ", ".join(f"characterRow{r}_checked" for r in MODULI) + "]\n")


def emit(d, kind):
    name = f"periodic_{d}_{kind}"
    exceptions = exceptions_for(d, kind)
    print(f"private def {name}_exceptions : List ExceptionWitness := [")
    print(",\n".join(f"  ⟨{p}, {s}, {str(second).lower()}⟩"
                     for p, s, second in exceptions) + "]\n")
    print(f"theorem {name} : Obstruction {d} {kind} :=")
    print("  obstruction_of_character_certificate (rows := characterRows)")
    print(f"    (exceptions := {name}_exceptions) (by decide) characterRows_checked")
    print("    (by rfl) (by rfl)\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--table", action="store_true")
    parser.add_argument("--gaps", type=int, nargs="*", default=[])
    parser.add_argument("--single", action="store_true")
    parser.add_argument("--part", type=int, choices=range(4))
    args = parser.parse_args()
    if args.table and (args.gaps or args.single or args.part is not None):
        parser.error("--table cannot be combined with certificate-generation options")
    if args.table:
        table()
    else:
        header("Erdos1058CharacterData", args.part)
        for d in args.gaps:
            if not 0 < d <= 210 or d % 2:
                parser.error("gaps must be positive even integers at most 210")
            for kind in (0, 1):
                emit(d, kind)
        if args.single:
            emit(0, 2)
    print("end Erdos1058.PeriodicSieveCertificate")


if __name__ == "__main__":
    main()
